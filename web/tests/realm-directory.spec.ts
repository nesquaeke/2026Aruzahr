import { test, expect } from '@playwright/test'

test('eight countries expose 33 original arms and linked house records', async ({ page }) => {
  await page.goto('/#/houses')
  const directory = page.getByTestId('realm-directory')
  await expect(directory).toBeVisible()
  await expect(directory.getByTestId('realm-house')).toHaveCount(33)
  await expect(directory.locator('.realm-overview-card')).toHaveCount(8)
  await directory.getByRole('button', { name: 'Vaeranth Hanedanı armasını büyüt' }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  await expect(dialog.locator('svg[data-motif="five-walls-sun"]')).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).not.toBeVisible()
  await directory.locator('[data-house-id="vaeranth"]').getByRole('link', { name: 'Hane kaydı' }).click()
  await expect(page).toHaveURL(/wiki\/(hane-vaeranth|vaeranth-hanedani)/)
  await expect(page.getByRole('heading', { name: /Vaeranth Hanedanı/ }).first()).toBeVisible()
})

test('country panels distinguish capital and country populations and preserve local titles', async ({ page }) => {
  await page.goto('/#/houses')
  const nav = page.getByRole('navigation', { name: 'Hanelerin ülkesi' })
  await nav.getByRole('button', { name: /Danstsud Krallığı/ }).click()
  const panel = page.getByTestId('realm-detail')
  await expect(panel.locator('.realm-demography')).toContainText('500.000')
  await panel.getByText('Geçit Lordu', { exact: true }).click()
  await expect(panel).toContainText('sekiz yılda bir')
  await expect(panel).toContainText('Dört yılda bir')
  await nav.getByRole('button', { name: /Murgul Ada Birliği/ }).click()
  await expect(panel.locator('.realm-demography')).toContainText('1.000.000')
  await nav.getByRole('button', { name: /Honud Kıyı Ocakları/ }).click()
  await expect(panel.locator('.realm-demography')).toContainText('500.000')
  await expect(panel.locator('.realm-demography > div').nth(2).locator('dd')).toHaveText('0')
  await expect(panel).toContainText('Hurnas Ithíl')
  await panel.getByText('Batıdan gelen soğuğun hesabı', { exact: true }).click()
  await expect(panel).toContainText('Soğuk batıdan doğuya ilerler')
})

test('house search finds rulers on mobile without document overflow', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/#/houses')
  await page.getByRole('searchbox', { name: 'Hanelerde ara' }).fill('Eyrik')
  await expect(page.getByTestId('realm-house')).toHaveCount(1)
  await expect(page.getByTestId('realm-house')).toContainText('Voss Kış Hanesi')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBeTruthy()
  await page.screenshot({ path: '../artifacts/houses-and-night/realm-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.getByRole('button', { name: 'Hane aramasını temizle' }).click()
  await page.screenshot({ path: '../artifacts/houses-and-night/realm-desktop.png', fullPage: true })
})
